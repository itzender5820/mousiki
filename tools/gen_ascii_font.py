#!/usr/bin/env python3
"""Generates src/video_fx_ascii_font.inc: the glyphs of the ASCII look (video effect 37) as 8 x 16 bitmaps.

The glyphs are the characters of DejaVu Sans Mono (Bitstream Vera licence: free to use and embed; the notice is written into the generated file),
drawn at 13.3 px so that the cell is 8 x 16, hinted to pixels. The set: the printable ASCII characters (no box-drawing lines or blocks: they join up into stripes; no Latin-1 letters or symbols since batch 275),
ordered by the ink they carry.

Usage:  python3 tools/gen_ascii_font.py [path to DejaVuSansMono.ttf]      (needs Pillow)
"""
import sys, os
from PIL import Image, ImageDraw, ImageFont

path = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf"
font = ImageFont.truetype(path, 13.3)
W, H = 8, 16

# only the printable ASCII characters (since batch 275): the Latin-1 letters and symbols (ß, ¶, Æ ...) filled the bright parts with shapes that do not look
# like ASCII art at all. Every one of them is kept (look-alikes too: at the size the look draws them they can be told apart, and they take turns).
chars = [chr(c) for c in range(0x21, 0x7F)]

def render(ch):
    im = Image.new("L", (W, H), 0)
    ImageDraw.Draw(im).text((0, 12), ch, font=font, fill=255, anchor="ls")
    # hinted to pixels: a pixel is on where the glyph covers at least about a third of it
    return [[1 if im.getpixel((x, y)) >= 90 else 0 for x in range(W)] for y in range(H)]

def vec(b):   # the matching resolution: 4 x 8 (2 x 2 blocks), coverage 0 .. 1
    return [sum(b[2 * j + dy][2 * i + dx] for dy in (0, 1) for dx in (0, 1)) / 4.0 for j in range(8) for i in range(4)]

kept = [([[0] * W for _ in range(H)], " ")]   # the space is the first glyph
vecs = [vec(kept[0][0])]
# the line glyphs the look draws edges with are always kept (they come first, so a look-alike is left out instead of them)
MUST = "-|/\\_"
for ch in MUST:
    b = render(ch)
    kept.append((b, ch))
    vecs.append(vec(b))
for ch in chars:
    if ch in MUST:
        continue
    b = render(ch)
    ink = sum(map(sum, b))
    if ink < 3:
        continue
    v = vec(b)
    kept.append((b, ch))
    vecs.append(v)

kept[1:] = sorted(kept[1:], key=lambda g: sum(map(sum, g[0])))
out = []
out.append("// Generated by tools/gen_ascii_font.py -- do not edit. The glyphs of the ASCII look (video effect 37): %d characters of DejaVu Sans Mono as 8 x 16 bitmaps" % len(kept))
out.append("// (one byte a row, the left pixel is bit 7), ordered by the ink they carry (the first is the space).")
out.append("// DejaVu fonts: Copyright (c) 2003 by Bitstream, Inc. All Rights Reserved. Bitstream Vera is a trademark of Bitstream, Inc. DejaVu changes are in the public domain.")
out.append("// The Bitstream Vera licence (THIRD_PARTY_LICENSES.txt) lets the Font Software be reproduced, distributed and sold as part of a larger software package.")
out.append("constexpr int kAsciiGlyphCount = %d;" % len(kept))
out.append("const uint8_t kAsciiGlyphs[kAsciiGlyphCount][16] = {")
for b, ch in kept:
    rows = ", ".join("0x%02X" % sum(b[y][x] << (7 - x) for x in range(W)) for y in range(H))
    label = ch if 0x20 <= ord(ch) < 0x7F and ch not in "\\" else "U+%04X" % ord(ch)
    out.append("    {%s}," % rows + ("   // " + label))
out.append("};")
out.append("// the character of every glyph (Unicode code points), in the same order")
out.append("const char32_t kAsciiGlyphCodes[kAsciiGlyphCount] = {" + ", ".join("0x%04X" % ord(ch) for b, ch in kept) + "};")
dest = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "video_fx_ascii_font.inc")
with open(dest, "w", encoding="utf-8") as f:
    f.write("\n".join(out) + "\n")
print("wrote %d glyphs to %s" % (len(kept), os.path.normpath(dest)))
