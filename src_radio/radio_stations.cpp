// Shared by preset and list names: no control characters, [ ] | (file syntax) become ( ) /, trimmed, at most
// `max_chars` characters (UTF-8 lead bytes are counted, a sequence is never cut in half).
static std::string clean_name(const std::string& raw, int max_chars) {
    std::string out;
    for (unsigned char ch : raw) {
        if (ch < 32 || ch == 127) continue;
        if (ch == '[') out += '(';
        else if (ch == ']') out += ')';
        else if (ch == '|') out += '/';
        else out += static_cast<char>(ch);
    }
    out = trim_ws(out);
    int chars = 0;
    for (size_t i = 0; i < out.size(); ++i) {
        if ((static_cast<unsigned char>(out[i]) & 0xC0) != 0x80 && ++chars > max_chars) { out.resize(i); break; }
    }
    return trim_ws(out);
}

std::string clean_preset_name(const std::string& raw) { return clean_name(raw, kPresetNameMax); }
std::string clean_list_name(const std::string& raw) { return clean_name(raw, kListNameMax); }

static std::vector<std::string> split_bar(const std::string& line) {
    std::vector<std::string> f;
    size_t pos = 0;
    while (true) {
        size_t bar = line.find('|', pos);
        f.push_back(trim_ws(line.substr(pos, bar == std::string::npos ? std::string::npos : bar - pos)));
        if (bar == std::string::npos) break;
        pos = bar + 1;
    }
    return f;
}

