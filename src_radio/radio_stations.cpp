// ---- stream URL comparison -------------------------------------------------------------------------
namespace {
struct UrlParts { std::string base; std::vector<std::string> query; };   // base: no scheme, lower-case host, no trailing "/"

UrlParts split_url(std::string u) {
    UrlParts p;
    const size_t hash = u.find('#');
    if (hash != std::string::npos) u.erase(hash);
    std::string q;
    const size_t qm = u.find('?');
    if (qm != std::string::npos) { q = u.substr(qm + 1); u.erase(qm); }
    const size_t sch = u.find("://");
    if (sch != std::string::npos) u.erase(0, sch + 3);
    const size_t slash = u.find('/');
    const size_t host_end = slash == std::string::npos ? u.size() : slash;
    for (size_t i = 0; i < host_end; ++i) u[i] = static_cast<char>(std::tolower(static_cast<unsigned char>(u[i])));
    while (!u.empty() && u.back() == '/') u.pop_back();
    p.base = u;
    size_t pos = 0;
    while (pos <= q.size() && !q.empty()) {
        size_t amp = q.find('&', pos);
        std::string kv = q.substr(pos, amp == std::string::npos ? std::string::npos : amp - pos);
        std::string key = kv.substr(0, kv.find('='));
        for (auto& c : key) c = static_cast<char>(std::tolower(static_cast<unsigned char>(c)));
        const bool noise = key.empty() || key == "aggregator" || key == "ref" || key == "source" || key == "src" || key.rfind("utm_", 0) == 0;
        if (!noise) p.query.push_back(kv);
        if (amp == std::string::npos) break;
        pos = amp + 1;
    }
    std::sort(p.query.begin(), p.query.end());
    return p;
}
} // namespace

bool same_stream_url(const std::string& a, const std::string& b) {
    if (a.empty() || b.empty()) return false;
    const UrlParts pa = split_url(a), pb = split_url(b);
    if (pa.base != pb.base) return false;
    const bool qa = a.find('?') != std::string::npos && a.find('?') + 1 < a.size();
    const bool qb = b.find('?') != std::string::npos && b.find('?') + 1 < b.size();
    if (!qa || !qb) return true;          // one side has no query at all: same mount
    return pa.query == pb.query;          // both have one: what is left after dropping tracking parameters must agree
}


// PATHS-tab overrides (empty = the default layout).
static std::string g_stations_file, g_lists_file, g_presets_file;

static void copy_if_missing(const std::string& from, const std::string& to) {
    if (to.empty() || from.empty() || from == to) return;
    std::error_code ec;
    if (fs::exists(to, ec) || !fs::exists(from, ec)) return;
    if (fs::path(to).has_parent_path()) fs::create_directories(fs::path(to).parent_path(), ec);
    fs::copy_file(from, to, ec);
}

static std::string default_file(const char* name) {
    const char* home = std::getenv("HOME");
    if (!home || !*home) home = std::getenv("USERPROFILE");
    return home && *home ? (fs::path(home) / ".config" / "mousiki" / name).string() : std::string(name);
}

static std::string alias_file_for(const std::string& stations_file) {
    return (fs::path(stations_file).parent_path() / "preset_names.txt").string();
}

std::string preset_names_path() {
    return alias_file_for(g_stations_file.empty() ? default_file("stations.txt") : g_stations_file);
}

bool save_preset_names(const std::vector<Station>& all) {
    const fs::path p = preset_names_path();
    std::error_code ec;
    if (p.has_parent_path()) fs::create_directories(p.parent_path(), ec);
    std::ostringstream o;   // written in one go at the end (write_text_atomic: never a cut-off file)
    o << "# Mousiki radio -- second names for the PRESETS pane: url<TAB>name (edited with SHIFT+c in the stations overlay)\n";
    for (const auto& st : all)
        if (!st.preset_name.empty()) o << st.url << '\t' << st.preset_name << '\n';
    return write_text_atomic(p, o.str());
}

static void apply_preset_names(std::vector<Station>& v) {
    std::ifstream in(preset_names_path());
    if (!in) return;
    std::string line;
    while (std::getline(in, line)) {
        if (!line.empty() && line.back() == '\r') line.pop_back();
        if (line.empty() || line[0] == '#') continue;
        const size_t tab = line.find('\t');
        if (tab == std::string::npos) continue;
        const std::string url = line.substr(0, tab), name = trim_ws(line.substr(tab + 1));
        for (auto& st : v) if (st.url == url) st.preset_name = name;
    }
}

void set_storage_files(const std::string& stations_file, const std::string& lists_file, const std::string& presets_file) {
    copy_if_missing(preset_names_path(), alias_file_for(stations_file));
    // copy from wherever the file is read from right now (the previous override, else the default place)
    copy_if_missing(g_stations_file.empty() ? default_file("stations.txt") : g_stations_file, stations_file);
    copy_if_missing(g_lists_file.empty() ? default_file("stationlists.txt") : g_lists_file, lists_file);
    copy_if_missing(g_presets_file.empty() ? default_file("presets.txt") : g_presets_file, presets_file);
    g_stations_file = stations_file; g_lists_file = lists_file; g_presets_file = presets_file;
}

static std::vector<Station> parse_file(const fs::path& p) {
    std::vector<Station> out;
    std::ifstream in(p);
    if (!in) return out;
    std::string line;
    while (std::getline(in, line)) {
        line = trim_ws(line);
        if (line.empty() || line[0] == '#') continue;
        // name | genre | country | codec | bitrate | url | [*] | [dial MHz]
        std::vector<std::string> f;
        size_t pos = 0;
        while (true) {
            size_t bar = line.find('|', pos);
            f.push_back(trim_ws(line.substr(pos, bar == std::string::npos ? std::string::npos : bar - pos)));
            if (bar == std::string::npos) break;
            pos = bar + 1;
        }
        if (f.size() < 6 || f[0].empty() || f[5].empty()) continue;
        Station s;
        s.name = f[0]; s.genre = f[1]; s.country = f[2]; s.codec_hint = f[3];
        s.bitrate_hint = muisc::atoi_safe(f[4].c_str());
        s.url = f[5];
        s.favorite = f.size() > 6 && f[6] == "*";
        s.dial_mhz = (f.size() > 7 && !f[7].empty()) ? std::atof(f[7].c_str()) : dial_for_name(s.name);
        out.push_back(std::move(s));
    }
    return out;
}

std::vector<Station> load_stations(std::string* source_out) {
    std::vector<fs::path> candidates;
    const char* home = std::getenv("HOME");
    if (!home || !*home) home = std::getenv("USERPROFILE");
    if (!g_stations_file.empty()) candidates.push_back(fs::path(g_stations_file));
    if (home && *home) candidates.push_back(fs::path(home) / ".config" / "mousiki" / "stations.txt");
    candidates.push_back(fs::path("stations.txt"));
    for (const auto& c : candidates) {
        std::error_code ec;
        if (!fs::exists(c, ec)) continue;
        auto v = parse_file(c);
        if (!v.empty()) {
            if (source_out) *source_out = c.string();
            apply_preset_names(v);
            return v;
        }
    }
    if (source_out) *source_out = "built-in defaults";
    return default_stations();
}

// ---- saving stations -----------------------------------------------------------------------------
static std::string clean_field(std::string v) {
    for (auto& c : v) if (c == '|' ) c = '/'; else if (static_cast<unsigned char>(c) < 32) c = ' ';
    return trim_ws(v);
}

static std::string station_line(const Station& s) {
    std::string l = clean_field(s.name) + " | " + clean_field(s.genre) + " | " + clean_field(s.country) + " | "
                  + clean_field(s.codec_hint) + " | " + std::to_string(std::max(0, s.bitrate_hint)) + " | " + clean_field(s.url);
    if (s.favorite) l += " | *";
    return l;
}

bool append_station_to_file(const Station& st, const std::vector<Station>& all, std::string* where, std::string* err) {
    std::vector<fs::path> candidates;
    const char* home = std::getenv("HOME");
    if (!home || !*home) home = std::getenv("USERPROFILE");
    if (!g_stations_file.empty()) candidates.push_back(fs::path(g_stations_file));
    if (home && *home) candidates.push_back(fs::path(home) / ".config" / "mousiki" / "stations.txt");
    candidates.push_back(fs::path("stations.txt"));
    // the file load_stations() used: the first candidate that exists and holds at least one station
    for (const auto& c : candidates) {
        std::error_code ec;
        if (!fs::exists(c, ec) || parse_file(c).empty()) continue;
        std::string tail;
        {
            std::ifstream in(c, std::ios::binary | std::ios::ate);
            if (in && in.tellg() > 0) { in.seekg(-1, std::ios::end); char last = 0; in.get(last); if (last != '\n') tail = "\n"; }
        }
        std::ofstream out(c, std::ios::app);
        if (!out) { if (err) *err = "cannot write " + path_utf8(c); return false; }
        out << tail << station_line(st) << "\n";
        if (where) *where = c.string();
        return static_cast<bool>(out);
    }
    // no stations.txt yet: create it from the whole in-memory list (defaults + the new station)
    fs::path target = !g_stations_file.empty() || (home && *home) ? candidates.front() : fs::path("stations.txt");
    std::error_code ec;
    if (target.has_parent_path()) fs::create_directories(target.parent_path(), ec);
    std::ofstream out(target);
    if (!out) { if (err) *err = "cannot write " + path_utf8(target); return false; }
    out << "# Mousiki radio mode -- station list (written by the radio; see radio/stations.txt for the format)\n"
           "# name | genre | country | codec | kbps | url | [*] favorite\n";
    for (const auto& s : all) out << station_line(s) << "\n";
    if (where) *where = target.string();
    return static_cast<bool>(out);
}

bool save_all_stations(const std::vector<Station>& all, std::string* where, std::string* err) {
    std::vector<fs::path> candidates;
    const char* home = std::getenv("HOME");
    if (!home || !*home) home = std::getenv("USERPROFILE");
    if (!g_stations_file.empty()) candidates.push_back(fs::path(g_stations_file));
    if (home && *home) candidates.push_back(fs::path(home) / ".config" / "mousiki" / "stations.txt");
    candidates.push_back(fs::path("stations.txt"));
    fs::path target = !g_stations_file.empty() || (home && *home) ? candidates.front() : fs::path("stations.txt");
    for (const auto& c : candidates) {
        std::error_code ec;
        if (fs::exists(c, ec) && !parse_file(c).empty()) { target = c; break; }
    }
    std::string head;   // the comment lines before the first station line stay
    {
        std::ifstream in(target);
        std::string line;
        while (in && std::getline(in, line)) {
            const std::string t = trim_ws(line);
            if (!t.empty() && t[0] != '#') break;
            head += line + "\n";
        }
    }
    if (head.empty())
        head = "# Mousiki radio mode -- station list (written by the radio; see radio/stations.txt for the format)\n"
               "# name | genre | country | codec | kbps | url | [*] favorite\n";
    std::error_code ec;
    if (target.has_parent_path()) fs::create_directories(target.parent_path(), ec);
    fs::path tmp = target;
    tmp += ".tmp";   // appended to the native path: no round trip through the ANSI code page
    {
        std::ofstream out(tmp, std::ios::binary);
        if (!out) { if (err) *err = "cannot write " + path_utf8(target); return false; }
        out << head;
        for (const auto& st : all) out << station_line(st) << "\n";
        if (!out) { if (err) *err = "cannot write " + path_utf8(target); return false; }
    }
    fs::rename(tmp, target, ec);
    if (ec) { fs::remove(tmp, ec); if (err) *err = "cannot write " + path_utf8(target); return false; }
    if (where) *where = target.string();
    return true;
}

int preset_slot_for_key(int key) {
    if (key <= 0 || key > 255) return -1;
    for (int i = 0; i < kPresetCount; ++i) if (kPresetKeys[i] == key) return i;
    return -1;
}

