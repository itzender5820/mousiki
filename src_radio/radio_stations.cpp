std::vector<StationList> load_station_lists(const std::vector<Station>& stations) {
    std::vector<StationList> lists;
    std::ifstream in(station_lists_path());
    if (!in) return lists;
    std::string line;
    StationList* cur = nullptr;
    while (std::getline(in, line)) {
        line = trim_ws(line);
        if (line.empty() || line[0] == '#') continue;
        if (line.front() == '[' && line.back() == ']') {
            StationList l;
            l.name = clean_list_name(line.substr(1, line.size() - 2));
            if (l.name.empty()) l.name = "List " + std::to_string(lists.size() + 1);
            lists.push_back(std::move(l));
            cur = &lists.back();
            continue;
        }
        if (!cur) continue;   // a station line before any [..] header: nothing to put it in
        const auto f = split_bar(line);   // url | name
        int found = -1;
        for (size_t i = 0; i < stations.size() && found < 0; ++i)
            if (!f[0].empty() && stations[i].url == f[0]) found = static_cast<int>(i);
        if (found < 0 && f.size() > 1)
            for (size_t i = 0; i < stations.size() && found < 0; ++i)
                if (stations[i].name == f[1]) found = static_cast<int>(i);
        if (found >= 0 && std::find(cur->items.begin(), cur->items.end(), found) == cur->items.end()) cur->items.push_back(found);
    }
    return lists;
}

bool save_station_lists(const std::vector<Station>& stations, const std::vector<StationList>& lists) {
    std::error_code ec;
    const fs::path p = station_lists_path();
    if (p.has_parent_path()) fs::create_directories(p.parent_path(), ec);
    std::ostringstream o;   // written in one go at the end (write_text_atomic: never a cut-off file)
    o << "# Mousiki radio station lists -- written by the STATION LISTS menu (Shift+K). [list name] followed by: url | station name\n";
    for (const auto& l : lists) {
        o << "\n[" << l.name << "]\n";
        for (int idx : l.items) {
            if (idx < 0 || idx >= static_cast<int>(stations.size())) continue;
            const Station& s = stations[static_cast<size_t>(idx)];
            o << s.url << " | " << s.name << "\n";
        }
    }
    return write_text_atomic(p, o.str());
}

PresetStore load_presets(const std::vector<Station>& stations) {
    PresetStore store;
    std::error_code ec;
    const fs::path p = presets_path();
    if (fs::exists(p, ec)) {
        // The key letters in the file name the slots. A file written by this version starts with an
        // "@keys <letters>" line saying which letters it used; one without it comes from before the
        // key change and used 1234567890qwertz. Slots are looked up in THAT string, so old presets
        // keep their slots instead of being dropped or shifted.
        std::string file_keys = "1234567890qwertz";
        {
            std::ifstream pre(p);
            std::string l;
            while (std::getline(pre, l)) {
                l = trim_ws(l);
                if (l.rfind("@keys", 0) == 0) { file_keys = trim_ws(l.substr(5)); break; }
            }
        }
        std::ifstream in(p);
        std::string line, active_name;
        PresetBank* cur = nullptr;
        while (std::getline(in, line)) {
            line = trim_ws(line);
            if (line.empty() || line[0] == '#') continue;
            if (line.rfind("@active", 0) == 0) { active_name = trim_ws(line.substr(7)); continue; }
            if (line.rfind("@keys", 0) == 0) continue;
            if (line.front() == '[' && line.back() == ']') {
                PresetBank b;
                b.name = clean_preset_name(line.substr(1, line.size() - 2));
                if (b.name.empty()) b.name = "Preset " + std::to_string(store.banks.size() + 1);
                store.banks.push_back(std::move(b));
                cur = &store.banks.back();
                continue;
            }
            // key | url | name
            const auto f = split_bar(line);
            if (f.size() < 2 || f[0].size() != 1) continue;
            const size_t at = file_keys.find(f[0][0]);
            if (at == std::string::npos || at >= static_cast<size_t>(kPresetCount)) continue;
            const int slot = static_cast<int>(at);
            if (!cur) {   // old file without headers: everything up to the first [..] is "Default"
                PresetBank b; b.name = "Default";
                store.banks.push_back(std::move(b));
                cur = &store.banks.back();
            }
            int found = -1;
            for (size_t i = 0; i < stations.size() && found < 0; ++i)
                if (!f[1].empty() && stations[i].url == f[1]) found = static_cast<int>(i);
            if (found < 0 && f.size() > 2)
                for (size_t i = 0; i < stations.size() && found < 0; ++i)
                    if (stations[i].name == f[2]) found = static_cast<int>(i);
            cur->slots[static_cast<size_t>(slot)] = found;   // a station that has disappeared leaves the slot empty
        }
        if (store.banks.empty()) { PresetBank b; b.name = "Default"; store.banks.push_back(std::move(b)); }
        for (size_t i = 0; i < store.banks.size(); ++i)
            if (!active_name.empty() && store.banks[i].name == active_name) store.active = static_cast<int>(i);
        return store;
    }
    // No presets.txt yet: the "*" stations of stations.txt become the first preset.
    PresetBank b; b.name = "Default";
    int slot = 0;
    for (size_t i = 0; i < stations.size() && slot < kPresetCount; ++i)
        if (stations[i].favorite) b.slots[static_cast<size_t>(slot++)] = static_cast<int>(i);
    store.banks.push_back(std::move(b));
    return store;
}

bool save_presets(const std::vector<Station>& stations, const PresetStore& store) {
    std::error_code ec;
    const fs::path p = presets_path();
    if (p.has_parent_path()) fs::create_directories(p.parent_path(), ec);
    std::ostringstream o;   // written in one go at the end (write_text_atomic: never a cut-off file)
    o << "# Mousiki radio presets -- written by the PRESETS menu (P). [preset name] followed by: key | url | station name\n";
    o << "@keys " << kPresetKeys << "\n";
    if (store.active >= 0 && store.active < static_cast<int>(store.banks.size()))
        o << "@active " << store.banks[static_cast<size_t>(store.active)].name << "\n";
    for (const auto& b : store.banks) {
        o << "\n[" << b.name << "]\n";
        for (int i = 0; i < kPresetCount && i < static_cast<int>(b.slots.size()); ++i) {
            const int idx = b.slots[static_cast<size_t>(i)];
            if (idx < 0 || idx >= static_cast<int>(stations.size())) continue;
            const Station& s = stations[static_cast<size_t>(idx)];
            o << kPresetKeys[i] << " | " << s.url << " | " << s.name << "\n";
        }
    }
    return write_text_atomic(p, o.str());
}

