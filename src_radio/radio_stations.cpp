double dial_for_name(const std::string& name) {
    uint32_t h = 5381;
    for (unsigned char c : name) h = h * 33u + c;
    const int steps = 206; // 87.5 .. 108.0 in 0.1 MHz steps
    return 87.5 + static_cast<double>(h % steps) / 10.0;
}

